export default function BottomNav({ role = 'student' }) {
  const pathname = usePathname();
  const items = navItems[role] || navItems.student;
  const dashboardRoot = `/dashboard/${role}`;

  const isActive = (href) => {
    if (href === dashboardRoot) {
      return pathname === href;
    }
    return pathname.startsWith(href);
  };

  return (
    <nav className={styles.bottomNav} role="navigation" aria-label="Bottom navigation">
      {items.map((item) => {
        const active = isActive(item.href);
        return (
          <Link
            key={item.href}
            href={item.href}
            className={`${styles.bottomNavItem} ${active ? styles.bottomNavItemActive : ''}`}
          >
            <span className={styles.bottomNavIcon}>{item.icon}</span>
            <span className={styles.bottomNavLabel}>{item.label}</span>
            {active && <span className={styles.bottomNavDot} />}
          </Link>
        );
      })}
    </nav>
  );
}
